"""Structural boundaries used by core. Adapters own I/O and configuration."""

from typing import Any, Protocol

from pozor.core.domain.context import ContextPack


class GenerationSettings(Protocol):
    @property
    def historical_token_budget(self) -> int: ...
    @property
    def per_topic_limit(self) -> int: ...
    @property
    def max_output_tokens(self) -> int: ...
    @property
    def context_size(self) -> int: ...
    @property
    def humor_v2_enabled(self) -> bool: ...
    @property
    def recent_token_budget(self) -> int: ...
    @property
    def session_token_budget(self) -> int: ...
    @property
    def conversation_token_budget(self) -> int: ...
    @property
    def dossier_token_budget(self) -> int: ...
    @property
    def token_reserve(self) -> int: ...


class ModelPort(Protocol):
    @property
    def settings(self) -> GenerationSettings: ...
    async def tokens(self, text: str, deadline: float) -> int: ...
    async def count(self, messages: list[dict[str, str]], deadline: float) -> int: ...
    async def complete_json(self, messages: list[dict[str, str]], deadline: float, *,
                            schema: dict[str, Any], temperature: float | None = None,
                            max_tokens: int | None = None) -> str: ...
    async def complete(self, messages: list[dict[str, str]], deadline: float) -> str: ...


class MessageStore(Protocol):
    async def context(self, *, chat_id: int, thread_id: int, target_id: int,
                      trigger_id: int, hint: str, target_label: str) -> ContextPack: ...
    async def entitled(self, chat: int, target: int, ids: list[str], now: float) -> bool: ...


class PromptStore(Protocol):
    def load(self, name: str) -> str: ...
    def version(self, name: str) -> str: ...


class Clock(Protocol):
    def time(self) -> float: ...
    def monotonic(self) -> float: ...


class Rng(Protocol):
    def sample(self, population: list[str], k: int) -> list[str]: ...
